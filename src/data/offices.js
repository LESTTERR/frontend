function office({
  id,
  name,
  category,
  floor,
  room = name,
  modelObjects = [],
  description,
  keywords = [],
  mapPosition,
}) {
  return {
    id,
    name,
    category,
    floor,
    room,
    hours: HOURS,
    description,
    keywords: [
      name,
      category,
      floor,
      room,
      ...modelObjects,
      ...keywords,
    ],
    mapPosition,
    modelObjects,
  };
}

