export function getTranslator(language) {
  const dictionary = translations[language] || translations.en;

  return (key, values = {}) => {
    const template = dictionary[key] ?? translations.en[key] ?? key;
    return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? "");
  };
}
